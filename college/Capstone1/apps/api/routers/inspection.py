"""Inspection lifecycle + vision endpoints (photo-first flow, ADR 0011).

Keeps the honesty contract at the API boundary: the overlay is only ever the
model's *predicted* mask, area is image-denominator, consent/training writes
flow exclusively through ``ConsentService``, and every analysis reply is
generated by the assistant service (LangChain when a key is set, an offline
stub otherwise). No cost or repair fields exist.
"""

